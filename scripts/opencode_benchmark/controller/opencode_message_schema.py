import math
import re


def _matches(value, schema):
    if '$ref' in schema:
        return _matches(value, SCHEMAS[schema['$ref'].removeprefix('#/components/schemas/')])
    if 'anyOf' in schema:
        return any(_matches(value, branch) for branch in schema['anyOf'])
    kind = schema['type']
    if kind == 'object':
        if not isinstance(value, dict):
            return False
        fields = schema.get('properties', {})
        return (set(schema.get('required', ())) <= value.keys()
                and (schema.get('additionalProperties', True) or not value.keys() - fields.keys())
                and all(_matches(item, fields[key]) for key, item in value.items() if key in fields))
    if kind == 'array':
        return isinstance(value, list) and all(_matches(item, schema['items']) for item in value)
    if kind == 'string':
        return (isinstance(value, str)
                and ('enum' not in schema or value in schema['enum'])
                and ('pattern' not in schema or re.search(schema['pattern'], value) is not None))
    if kind == 'null':
        return value is None
    if kind == 'boolean':
        return type(value) is bool
    if kind in ('number', 'integer'):
        numeric = type(value) is int or kind == 'number' and type(value) is float
        return (numeric and (type(value) is not float or math.isfinite(value))
                and ('minimum' not in schema or value >= schema['minimum'])
                and ('maximum' not in schema or value <= schema['maximum']))
    raise ValueError('unsupported pinned schema keyword')


def non_tool_record(message):
    """Validate a complete non-assistant record; never infer execution success."""
    if not isinstance(message, dict) or not isinstance(message.get('type'), str):
        raise ValueError('unsupported pinned API message schema')
    name = MESSAGE_SCHEMAS.get(message['type'])
    if name is None or not _matches(message, SCHEMAS[name]):
        raise ValueError('invalid or unsupported pinned non-tool message record')
    if message['type'] == 'idle':
        # Preserve the existing idle evidence shape for earlier consumers.
        return {'id': message['id'], 'outcome': message['outcome'], 'has_error': 'error' in message}
    record = {'id': message['id'], 'type': message['type']}
    for field in ('agent', 'model', 'previous', 'projectID', 'subpath', 'location',
                  'skill', 'name', 'shellID', 'command', 'status', 'exit', 'reason'):
        if field in message:
            record[field] = message[field]
    if 'error' in message:
        record['has_error'] = True
    return record

